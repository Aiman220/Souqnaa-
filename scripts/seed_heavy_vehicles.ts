async function seedHeavyVehicles() {
  console.log('Seeding Heavy & Bulky Vehicle Classes...');
  for (const vehicle of DEFAULT_HEAVY_VEHICLES) {
    await prisma.heavyVehicleClass.upsert({
      where: { code: vehicle.code },
      update: vehicle,
      create: vehicle,
    });
    console.log(`- Upserted vehicle class: ${vehicle.code} (${vehicle.nameAr})`);
  }
  console.log('All Heavy Vehicle Classes successfully seeded.');
  await prisma.$disconnect();
}

seedHeavyVehicles().catch((e) => {
  console.error(e);
  process.exit(1);
});
